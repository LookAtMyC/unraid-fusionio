#!/usr/bin/env python3
"""Generate fusionio.plg from the files in src/.

Every file in src/ is embedded in the plugin, so the plugin needs no
downloads at boot except the driver itself (which is cached on the flash
drive). Run after changing anything in src/:

    python3 build/make-plg.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "fusionio.plg"

VERSION = "2026.11.27a"
REPO = "LookAtMyC/unraid-fusionio"
PLUGIN_DIR = "/usr/local/emhttp/plugins/fusionio"

CHANGES = """\
###2026.11.27
- First release.
- Loads the community iomemory-vsl (VSL3) driver for Fusion-io / SanDisk ioDrive, ioDrive2, ioScale and ioScale2 cards.
- New "Fusion-io Devices" section on the Main page: card health, mount/unmount, auto mount, format.
- Per card "Array / pool" switch: shows the card as a normal disk so it can be used in the array or a pool.
- Dashboard tile with temperature, power and usage of each card.
"""

INSTALL = r"""
REPO="@REPO@"
DIR="/boot/config/plugins/fusionio"
KV="$(uname -r)"
KO="$DIR/iomemory-vsl-$KV.ko"
URL="https://github.com/$REPO/releases/download/$KV/iomemory-vsl-$KV.ko"

say() { echo "fusionio: $*"; logger -t fusionio "$*"; }

mkdir -p "$DIR"
ln -sf @PLUGIN_DIR@/scripts/fusionio /usr/local/sbin/fusionio

if ! lsmod | grep -q '^iomemory_vsl'; then
  if [ ! -f "$KO" ]; then
    say "downloading driver for kernel $KV"
    ok=""
    for try in 1 2 3 4 5; do
      if wget -q -T 15 -O "$KO.part" "$URL" && wget -q -T 15 -O "$KO.sha256" "$URL.sha256"; then
        ok=1; break
      fi
      sleep 5
    done
    if [ -z "$ok" ]; then
      rm -f "$KO.part" "$KO.sha256"
      say "no driver available for kernel $KV yet (or no network)."
      say "builds appear at https://github.com/$REPO/releases about a day after a new Unraid release."
      exit 0
    fi
    want="$(cut -d' ' -f1 "$KO.sha256")"
    got="$(sha256sum "$KO.part" | cut -d' ' -f1)"
    if [ "$want" != "$got" ]; then
      rm -f "$KO.part" "$KO.sha256"
      say "checksum mismatch for downloaded driver, not loading it"
      exit 0
    fi
    mv "$KO.part" "$KO"
    rm -f "$KO.sha256"
  fi

  # Drop drivers built for other kernels (left over from earlier Unraid versions).
  find "$DIR" -maxdepth 1 -name 'iomemory-vsl-*.ko' ! -name "iomemory-vsl-$KV.ko" -delete

  if ! insmod "$KO"; then
    say "loading the driver failed, see: dmesg | grep fio"
    exit 0
  fi
  # give the cards a moment to attach
  for i in $(seq 1 30); do ls /dev/fio[a-z] >/dev/null 2>&1 && break; sleep 1; done
  sleep 2
  say "driver loaded; cards: $(ls /dev/fio[a-z] 2>/dev/null | tr '\n' ' ')"
fi

# apply per-card settings (array/pool mode, auto mount)
/usr/local/sbin/fusionio boot
exit 0
"""

REMOVE = r"""
rm -rf @PLUGIN_DIR@ /usr/local/sbin/fusionio
rm -rf /boot/config/plugins/fusionio
echo "fusionio: plugin removed. The driver stays loaded until the next restart."
"""


def cdata(text: str) -> str:
    assert "]]>" not in text, "file contains ]]>"
    return "<![CDATA[\n" + text.rstrip("\n") + "\n]]>"


def fill(s: str) -> str:
    return s.replace("@REPO@", REPO).replace("@PLUGIN_DIR@", PLUGIN_DIR)


parts = [f"""<?xml version='1.0' standalone='yes'?>
<!-- Generated by build/make-plg.py from src/. Edit those files, not this one. -->
<!DOCTYPE PLUGIN [
<!ENTITY name      "fusionio">
<!ENTITY author    "LookAtMyC">
<!ENTITY version   "{VERSION}">
<!ENTITY gitURL    "https://github.com/{REPO}">
<!ENTITY pluginURL "https://raw.githubusercontent.com/{REPO}/main/fusionio.plg">
]>

<PLUGIN name="&name;"
        author="&author;"
        version="&version;"
        pluginURL="&pluginURL;"
        support="&gitURL;/issues"
        min="7.1.4"
        icon="bolt">

<CHANGES>
{CHANGES}</CHANGES>
"""]

for f in sorted(p for p in SRC.rglob("*") if p.is_file()):
    rel = f.relative_to(SRC).as_posix()
    mode = ' Mode="0755"' if rel.startswith("scripts/") else ""
    parts.append(f'<FILE Name="{PLUGIN_DIR}/{rel}"{mode}>\n<INLINE>\n'
                 f'{cdata(f.read_text(encoding="utf-8"))}\n</INLINE>\n</FILE>\n')

parts.append(f'<!-- Runs on install and on every boot. -->\n<FILE Run="/bin/bash">\n<INLINE>\n{cdata(fill(INSTALL))}\n</INLINE>\n</FILE>\n')
parts.append(f'<FILE Run="/bin/bash" Method="remove">\n<INLINE>\n{cdata(fill(REMOVE))}\n</INLINE>\n</FILE>\n')
parts.append("</PLUGIN>\n")

OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
print(f"wrote {OUT.relative_to(ROOT)}")
